NUM_NODES = 14

EDGES = [
    (0, 1), (0, 2), (0, 5),
    (1, 2), (1, 3),
    (2, 8),
    (3, 4), (3, 6), (3, 13),
    (4, 9),
    (5, 6), (5, 10),
    (6, 7),
    (7, 8),
    (8, 9),
    (9, 11), (9, 12),
    (10, 11), (10, 12),
    (11, 13),
    (12, 13),
]


def build_adjacency():
    adj = {i: [] for i in range(NUM_NODES)}
    for u, v in EDGES:
        adj[u].append(v)
        adj[v].append(u)
    return adj


ADJACENCY = build_adjacency()
